merge into program_language_requirements d
using (
  with tokens as (
    select p.program_id,
           trim(regexp_substr(m.language_requirements_std, '[^|]+', 1, t.lvl)) as token
    from master_programs m
    join programs p
      on p.program_name = trim(m.program_name)
     and p.university_id = (select u.university_id
                            from universities u
                            where u.university_name = trim(m.university_name))
    cross join (select level as lvl from dual connect by level <= 10) t
    where m.language_requirements_std is not null
      and regexp_substr(m.language_requirements_std, '[^|]+', 1, t.lvl) is not null
  ),
  parsed as (
    select program_id,
           regexp_replace(trim(regexp_replace(token, '([0-9]+(\.[0-9]+)?)$', '')), '\s+', ' ') as test_name_norm,
           regexp_substr(token, '([0-9]+(\.[0-9]+)?)$') as score_str
    from tokens
  ),
  rolled as (
    select
      p.program_id,
      lt.language_test_id,
      max(case when score_str is not null then to_number(score_str) end) as required_score_number
    from parsed p
    join language_tests lt
      on lt.test_name = p.test_name_norm
    where p.test_name_norm is not null
    group by p.program_id, lt.language_test_id
  )
  select program_id, language_test_id, required_score_number
  from rolled
) s
on (d.program_id = s.program_id and d.language_test_id = s.language_test_id)
when not matched then insert (program_id, language_test_id, required_score_number, score_text)
values (s.program_id, s.language_test_id, s.required_score_number, null);

insert into program_study_options (program_id, study_mode_id, duration_months)
select
  t.program_id,
  sm.study_mode_id,
  max(t.duration_months) as duration_months
from (
  select
    p.program_id,
    trim(regexp_substr(m.study_mode, '[^|]+', 1, lvl)) as mode_token,
    case
      when m.study_mode_months is not null
           and regexp_like(trim(m.study_mode_months), '^[0-9]+(\.[0-9]+)?$')
      then to_number(trim(m.study_mode_months))
      else null
    end as duration_months
  from master_programs m
  join programs p
    on p.program_name = trim(m.program_name)
   and p.university_id = (
         select u.university_id
         from universities u
         where u.university_name = trim(m.university_name)
       )
  cross join (select level as lvl from dual connect by level <= 5)
  where m.study_mode is not null
    and regexp_substr(m.study_mode, '[^|]+', 1, lvl) is not null
) t
join study_modes sm
  on sm.study_mode_name = t.mode_token
where not exists (
  select 1
  from program_study_options x
  where x.program_id = t.program_id
    and x.study_mode_id = sm.study_mode_id
)
group by t.program_id, sm.study_mode_id;


