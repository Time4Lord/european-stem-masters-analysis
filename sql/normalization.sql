create table universities (
  university_id    number generated by default as identity primary key,
  university_name  varchar2(300) not null,
  constraint uq_universities_name unique (university_name)
);

create table locations (
  location_id  number generated by default as identity primary key,
  city         varchar2(200),
  country      varchar2(200),
  constraint uq_locations_city_country unique (city, country)
);

create table degrees (
  degree_id   number generated by default as identity primary key,
