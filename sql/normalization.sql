  constraint uq_degrees_tag unique (degree_tag)
);

create table delivery_types (
  delivery_type_id   number generated by default as identity primary key,
  delivery_type_name varchar2(50) not null,
  constraint uq_delivery_types_name unique (delivery_type_name)
);

create table study_modes (
  study_mode_id   number generated by default as identity primary key,
  study_mode_name varchar2(50) not null,
  constraint uq_study_modes_name unique (study_mode_name)
);

create table languages (
  language_id   number generated by default as identity primary key,
  language_name varchar2(100) not null,
  constraint uq_languages_name unique (language_name)
);

create table disciplines (
  discipline_id   number generated by default as identity primary key,
  discipline_name varchar2(200) not null,
  constraint uq_disciplines_name unique (discipline_name)
);

create table language_tests (
  language_test_id number generated by default as identity primary key,
  test_name        varchar2(100) not null,
  constraint uq_language_tests_name unique (test_name)
);


create table programs (
  program_id                    number generated by default as identity primary key,
  university_id                 number not null,
  degree_id                     number,
  location_id                   number,

  program_name                  varchar2(400) not null,
  credits_ects                  number,
  review_score                  number(4,2),
  review_count                  number,
  thesis_required               char(1) check (thesis_required in ('Y','N')),
  internship_mandatory          char(1) check (internship_mandatory in ('Y','N')),

  industry_partnership_level    varchar2(10) check (industry_partnership_level in ('none','some','strong')),
  career_services_strength      varchar2(10) check (career_services_strength in ('weak','avg','strong')),
  alumni_network_strength       varchar2(10) check (alumni_network_strength in ('weak','avg','strong')),

  program_matriculation_fee     number,
  tuition_amount_eur            number,
  living_cost_eur               number,

  constraint uq_programs_univ_name unique (university_id, program_name),
  constraint fk_programs_university   foreign key (university_id)    references universities(university_id),
  constraint fk_programs_degree       foreign key (degree_id)        references degrees(degree_id),
  constraint fk_programs_location     foreign key (location_id)      references locations(location_id)
);


create table program_study_options (
  program_study_option_id number generated by default as identity primary key,
  program_id              number not null,
