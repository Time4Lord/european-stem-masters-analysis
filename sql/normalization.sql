merge into language_tests d
using (
  select distinct
         case
           when regexp_like(
                  trim(regexp_replace(token, '\s*[0-9]+([.,][0-9]+)?\s*$', '')),
                  '^TOEFL', 'i'
                )
           then 'TOEFL iBT'
           when regexp_like(
                  trim(regexp_replace(token, '\s*[0-9]+([.,][0-9]+)?\s*$', '')),
                  'DUOLINGO', 'i'
                )
           then 'Duolingo English Test'
           else regexp_replace(
                  trim(regexp_replace(token, '\s*[0-9]+([.,][0-9]+)?\s*$', '')),
                  '[[:space:]]+', ' '
                )
         end as test_name
  from (
    select trim(regexp_substr(m.language_requirements_std, '[^|]+', 1, t.lvl)) as token
    from master_programs m
    cross join (select level as lvl from dual connect by level <= 10) t
    where m.language_requirements_std is not null
      and regexp_substr(m.language_requirements_std, '[^|]+', 1, t.lvl) is not null
  )
) s
on (d.test_name = s.test_name)
when not matched then
  insert (test_name) values (s.test_name);



merge into programs d
using (
  select *
  from (
    select
      u.university_id,
      trim(m.program_name) as program_name,
      dg.degree_id,
      l.location_id,
      cast(nullif(trim(m.credits_ects), '') as number)     as credits_ects,
      cast(nullif(trim(m.review_score), '') as number)     as review_score,
      cast(nullif(trim(m.review_count), '') as number)     as review_count,

      case lower(trim(m.thesis_required))
        when 'yes' then 'Y' when 'y' then 'Y' when 'true' then 'Y' else 'N' end as thesis_required,
      case lower(trim(m.internship_mandatory))
        when 'yes' then 'Y' when 'y' then 'Y' when 'true' then 'Y' else 'N' end as internship_mandatory,

      lower(trim(m.industry_partnership_level)) as industry_partnership_level,
      lower(trim(m.career_services_strength))   as career_services_strength,
      lower(trim(m.alumni_network_strength))    as alumni_network_strength,

      cast(nullif(trim(m.program_matriculation_fee), '') as number) as program_matriculation_fee,
      cast(nullif(trim(m.tuition_amount_eur), '') as number)        as tuition_amount_eur,
      cast(nullif(trim(m.living_cost_eur), '') as number)           as living_cost_eur,

      row_number() over (
        partition by u.university_id, trim(m.program_name)
        order by
          nvl(cast(nullif(trim(m.review_count), '') as number), 0) desc,
          nvl(cast(nullif(trim(m.review_score), '') as number), -1) desc,
          trim(m.delivery_type_std) nulls last
      ) as rn
    from master_programs m
    join universities   u  on u.university_name = trim(m.university_name)
    left join degrees   dg on dg.degree_tag     = trim(m.degree_tag_clean)
    left join locations l  on l.city            = trim(m.city) and l.country = trim(m.country)
    where m.program_name is not null
  )
  where rn = 1
) s
on (d.university_id = s.university_id and d.program_name = s.program_name)
when not matched then insert (
  university_id, degree_id, location_id,
  program_name, credits_ects, review_score, review_count,
  thesis_required, internship_mandatory,
  industry_partnership_level, career_services_strength, alumni_network_strength,
  program_matriculation_fee, tuition_amount_eur, living_cost_eur
) values (
  s.university_id, s.degree_id, s.location_id,
  s.program_name, s.credits_ects, s.review_score, s.review_count,
  s.thesis_required, s.internship_mandatory,
  s.industry_partnership_level, s.career_services_strength, s.alumni_network_strength,
  s.program_matriculation_fee, s.tuition_amount_eur, s.living_cost_eur
);

create table program_delivery_types (
  program_id       number not null,
  delivery_type_id number not null,
  constraint pk_program_delivery_types primary key (program_id, delivery_type_id),
  constraint fk_pdt_prog foreign key (program_id) references programs(program_id) on delete cascade,
  constraint fk_pdt_del  foreign key (delivery_type_id) references delivery_types(delivery_type_id)
);

merge into program_delivery_types tgt
using (
  select distinct p.program_id, dt.delivery_type_id
  from master_programs m
  join programs p
    on p.program_name = trim(m.program_name)
   and p.university_id = (
         select u.university_id from universities u where u.university_name = trim(m.university_name)
       )
  cross join (select level as lvl from dual connect by level <= 5)
  join delivery_types dt
    on dt.delivery_type_name = trim(regexp_substr(m.delivery_type_std, '[^|]+', 1, lvl))
  where m.delivery_type_std is not null
    and regexp_substr(m.delivery_type_std, '[^|]+', 1, lvl) is not null
) src
on (tgt.program_id = src.program_id and tgt.delivery_type_id = src.delivery_type_id)
when not matched then
  insert (program_id, delivery_type_id)
  values (src.program_id, src.delivery_type_id);


